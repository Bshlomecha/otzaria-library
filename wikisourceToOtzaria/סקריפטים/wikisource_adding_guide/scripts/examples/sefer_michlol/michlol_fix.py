# -*- coding: utf-8 -*-
"""michlol_fix.py - תיקוני שגיאות הקלדה מקומיות בטקסט הוויקיטקסט של "ספר מכלול (רד"ק)" (דוגמה).

מיובא על ידי ws_book_michlol.py ומוחל על כל דף מיד לאחר הורדתו, לפני ההמרה. הכלל: מתקנים *רק* שגיאת סימון/תבנית
(לא לשון המקור), כל תיקון נספר ב-FIX_LOG ומופיע בדוח ("תיקוני מקור מקומיים"). דפוס לשימוש כשדף מקור שבור 
(תבנית שבורה, }} מיותר) מפיל את ההמרה או משאיר שאריות.
"""
import re

FIX_LOG = {}


def michlol_fix(t: str) -> str:
    """תיקוני שגיאות הקלדה מקומיות בוויקי (נספרים ב-FIX_LOG)."""
    def sub(pat, rep, what, flags=0):
        nonlocal t
        t2, n = re.subn(pat, rep, t, flags=flags)
        if n:
            FIX_LOG[what] = FIX_LOG.get(what, 0) + n
            t = t2

    # כותרת מיכל-ההערות שבתוך noinclude (ההערות עצמן בספר ההערות)
    sub(r"(?m)^=+[ \t]*נימוקי רבי אליהו בחור[ \t]*=+[ \t]*\n(?=[ \t]*\{\{הערות שוליים\}\})", "",
        "הוסרה כותרת 'נימוקי רבי אליהו בחור' (מיכל noinclude)")
    # תבנית הערה שבורה
    sub(r'\{\{(א"א כי זה נמצא לרוב[^{}]*)\}\}', r"{{הערה|\1}}", "תבנית שבורה {{א\"א כי...}} -> {{הערה|...}}")
    # }} מיותר
    sub(r"(חַסְדּוֹ'''\}\})\}\}( \{\{ק\|\(\[\[תהלים קז א)", r"\1\2", "'}}' מיותר")
    # {{ק|( שנשחק ל-{{
    sub(r"\{\{(ספר מכלול[^{}|\[\]]*/לפי דפים/[^{}|\[\]]+\|לעיל [^{}|\[\]]*\]\]\)\}\})",
        lambda m: "{{ק|([[" + m.group(1), "'{{ק|([[' שנשחק ל-'{{'")
    return t
