#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""המרת "פחד יצחק חלק ט" של ים החכמה משורות דפוס לערכים.

בעיית המקור
-----------
הקובץ (נמשך באוקטובר 2026, 7,414 שורות) הוא OCR בלי תגים: שורה לכל שורת דפוס
(60–70 תווים), בלי סימון סוף פסקה. אין בו סימני עמוד או כותרות רצות, אבל יש שתי
שורות זבל של OCR (`UGUU`, `2 22 22`). הערכים מסודרים לפי א"ב וכולם בחלק הזה
פותחים באות פ, אבל טעויות ד/ר של ה־OCR (פריון/פדיון) שוברות את הסדר, ולכן אי
אפשר להשתמש בו לזיהוי ערכים.

מה הסקריפט עושה
---------------
1. שורה 1 = `<h1>פחד יצחק חלק ט</h1>`, שורה 2 = המחבר.
2. מוחק את שתי שורות הזבל (שורות שאין בהן אות עברית).
3. מחבר שורות דפוס לפסקה. פסקה חדשה נפתחת בשורה שמתחילה באות פ כשהשורה שלפניה
   נגמרת ב־`.`/`:` — כלומר בערך חדש — או אחרי שורה קצרה (<45 תווים, שארית שורה
   בדפוס) שנגמרת ב־`.`/`:`, כמו ב־chazon_ish_nezikin_reflow.py. טעות לכאן היא
   פיצול בסוף משפט, ולכאן — שני ערכים בפסקה אחת; בשני המקרים לא נמחקת מילה.
   ערך שמתחיל באמצע שורת דפוס
   (`ע"ב. פועלים עיין.`) נשאר בפסקה של קודמו.
   שורת המקור השנייה (`פאה`, לפני הערך הראשון) נשארת שורה בפני עצמה.
4. בדיקת שימור: הטקסט בלי רווחים זהה למקור בניכוי שורות הזבל.

אין כותרות לערכים: גבול המילה הראשית אינו מסומן בטקסט (`פגול ונותר`, `פת שחרית עיין:`).

שימוש
-----
    python3 -X utf8 pachad_yitzchak_reflow.py SRC.txt OUT.txt
"""
import re, sys

TITLE = 'פחד יצחק חלק ט'
AUTHOR = 'יצחק חזקיה לאמפרונטי'
SRC, OUT = sys.argv[1:3]
L = [l.strip() for l in open(SRC, encoding='utf-8').read().split('\n')]
assert L[0] == TITLE, L[0]
junk = [l for l in L[1:] if l and not re.search(r'[א-ת]', l)]
body = [l for l in L[1:] if l and re.search(r'[א-ת]', l)]

paras = [body[0]]
cur = []
for line in body[1:]:
    if cur and re.search(r'[.:][)\]]?$', cur[-1]) and (line.startswith('פ') or len(cur[-1]) < 45):
        paras.append(' '.join(cur))
        cur = []
    cur.append(line)
paras.append(' '.join(cur))

out = [f'<h1>{TITLE}</h1>', AUTHOR] + paras
open(OUT, 'w', encoding='utf-8').write('\n'.join(out) + '\n')

strip = lambda s: re.sub(r'\s+', '', s)
if strip(''.join(body)) != strip(''.join(paras)):
    sys.exit('שימור טקסט נכשל')
print(f'{len(L)} שורות מקור → {len(out)} שורות; נמחקו {len(junk)} שורות זבל: {junk}')
